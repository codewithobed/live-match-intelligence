    import matplotlib.pyplot as plt
    from matplotlib.patches import FancyBboxPatch, Rectangle

    if len(team_names) < 2:
        raise ValueError("team_names must contain two team names.")

    team_1 = str(team_names[0])
    team_2 = str(team_names[1])

    minute = match_minute
    if minute is None:
        minute = base_features.get("snapshot_minute", prediction.get("model_minute", 0))
