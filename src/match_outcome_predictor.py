    ax.add_patch(Rectangle((0.03, 0.925), 0.94, 0.045, facecolor=navy, edgecolor=navy))
    ax.text(0.05, 0.947, "LIVE MATCH INTELLIGENCE", color="white",
            fontsize=19, fontweight="bold", va="center")
    ax.text(0.95, 0.947, "PREDICTIVE MODEL", color="white",
            fontsize=10, ha="right", va="center")

    ax.text(0.5, 0.885, title, color=navy, fontsize=24,
            fontweight="bold", ha="center")
    ax.text(0.5, 0.852, f"{team_1} {home_goals}  —  {away_goals} {team_2}",
            fontsize=17, fontweight="bold", ha="center", color=dark)
    ax.text(0.5, 0.825,
            f"Match state: {minute}'  |  Model checkpoint: {model_minute}'  |  Variant: {variant}",
            fontsize=10.5, ha="center", color=grey)

    # Team identities with automatic badge resolution.
    _add_predictive_team_badge(
        fig,
        team_1,
        0.085,
        0.798,
        0.060,
        0.060,
    )
    _add_predictive_team_badge(
        fig,
        team_2,
        0.855,
        0.798,
        0.060,
        0.060,
    )

    ax.text(
        0.155,
        0.825,
        team_1.upper(),
        fontsize=10.5,
        fontweight="bold",
        color=navy,
        ha="left",
        va="center",
    )
    ax.text(
        0.845,
        0.825,
        team_2.upper(),
        fontsize=10.5,
        fontweight="bold",
        color=navy,
        ha="right",
        va="center",
    )

    # Outcome probability section
    ax.add_patch(FancyBboxPatch((0.055, 0.645), 0.89, 0.145,
                                boxstyle="round,pad=0.008,rounding_size=0.012",
                                facecolor=pale, edgecolor=blue, linewidth=1.2))
    ax.text(0.5, 0.765, "ESTIMATED MATCH OUTCOME", color=navy,
            fontsize=13, fontweight="bold", ha="center")

    labels = [f"{team_1} Win", "Draw", f"{team_2} Win"]
    probs = [p1, pd, p2]
    colours = [blue, draw_colour, navy]
