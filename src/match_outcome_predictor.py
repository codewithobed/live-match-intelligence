    for x, label, prob, colour in zip(xs, labels, probs, colours):
        ax.text(x, 0.723, f"{prob*100:.1f}%", ha="center", va="center",
                fontsize=26, fontweight="bold", color=colour)
        ax.text(x, 0.690, label, ha="center", va="center",
                fontsize=11, fontweight="bold", color=dark)

    # Stacked probability bar
