    if total <= 0:
        p1 = pd = p2 = 1 / 3
    else:
        p1, pd, p2 = p1 / total, pd / total, p2 / total

    home_goals = int(float(base_features.get("home_goals", 0) or 0))
    away_goals = int(float(base_features.get("away_goals", 0) or 0))
    home_xg = float(base_features.get("home_xg", 0.0) or 0.0)
    away_xg = float(base_features.get("away_xg", 0.0) or 0.0)
    home_shots = int(float(base_features.get("home_shots", 0) or 0))
    away_shots = int(float(base_features.get("away_shots", 0) or 0))
    home_pressures = int(float(base_features.get("home_pressures", 0) or 0))
    away_pressures = int(float(base_features.get("away_pressures", 0) or 0))
    home_recent_xg = float(base_features.get("home_recent_xg", 0.0) or 0.0)
    away_recent_xg = float(base_features.get("away_recent_xg", 0.0) or 0.0)
    momentum_diff = float(base_features.get("momentum_difference", 0.0) or 0.0)

    model_minute = prediction.get("model_minute", "N/A")
    variant = prediction.get("model_variant", "Unknown")
    accuracy = prediction.get("validation_accuracy")
    macro_f1 = prediction.get("validation_macro_f1")
    log_loss = prediction.get("validation_log_loss")

    fig = plt.figure(figsize=(16, 10), dpi=140)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_axis_off()

    navy = "#10386f"
    blue = "#2878c8"
    light_blue = "#eaf3fb"
    pale = "#f7f9fc"
    dark = "#111111"
    grey = "#666666"
    border = "#bfd0e3"
    draw_colour = "#9aa6b2"

